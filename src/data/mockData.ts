const MD_ROOT_NODE_ID = 'org-md-root';

function inferOrgLevel(position: string): OrgChartNode['level'] {
  if (/manager|ผู้จัดการ|หัวหน้าแผนก/i.test(position)) return 'mgr';
  if (/senior|อาวุโส/i.test(position)) return 'sr_officer';
  return 'officer';
}

